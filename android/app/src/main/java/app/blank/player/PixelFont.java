    private PixelFont() {}

    static boolean has(int codePoint) {
        return Arrays.binarySearch(CODES, codePoint) >= 0;
    }

    /** Column bitmasks for the glyph, trimmed of empty columns on the right. Null when the font has no such glyph. */
    static int[] glyph(int codePoint) {
        int at = Arrays.binarySearch(CODES, codePoint);
        if (at < 0) return null;
        long packed = BITS[at];
        int[] columns = new int[5];
        int used = 0;
        for (int i = 0; i < 5; i++) {
            columns[i] = (int) ((packed >> (7 * i)) & 0x7F);
            if (columns[i] != 0) used = i + 1;
        }
        if (used == 0) return new int[SPACE_WIDTH];
        return Arrays.copyOf(columns, used);
    }
